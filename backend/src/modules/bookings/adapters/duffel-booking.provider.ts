import { Injectable } from '@nestjs/common';
import {
  BookingProvider,
  BookingRevalidation,
  CancelBookingInput,
  CreatedBooking,
  CreateBookingInput,
} from '../../../common/providers/booking-provider.interface';
import { ProviderResult } from '../../../common/providers/provider.result';
import { DuffelService } from '../../duffel/duffel.service';

/**
 * P3-D4 — the internal traveller shape is NOT Duffel's order shape. Duffel's
 * `CreateOrderPassenger` (docs "Order Request Passenger") requires `id`,
 * `given_name`, `family_name`, `gender`, `title`, `born_on`, `email` and
 * `phone_number` for EVERY passenger. This adapter maps the collected fields
 * to those exact property names and fails BEFORE the provider call when a
 * required field has no real source — it never invents a title, a date of
 * birth, a per-passenger contact, or an offer-request passenger id.
 */

/** Duffel's accepted titles (`DuffelPassengerTitle`). */
const DUFFEL_TITLES = new Set(['mr', 'ms', 'mrs', 'miss', 'dr']);

/** Duffel's accepted identity-document types (`PassengerIdentityDocumentType`). */
const DUFFEL_DOCUMENT_TYPES = new Set(['passport', 'tax_id']);

/**
 * A passenger on the stored Duffel offer (`OfferPassenger`, SDK 4.31.0).
 * `id` is the ONLY valid `id` on an order passenger — it is generated by the
 * original offer request and recovered from the stored offer id.
 */
interface DuffelOfferPassenger {
  id: string;
  type: 'adult' | 'child' | 'infant_without_seat' | null;
  age: number | null;
}

/** Maps the internal traveller classification onto Duffel's offer-passenger type. */
const DUFFEL_OFFER_TYPE: Record<string, DuffelOfferPassenger['type']> = {
  adult: 'adult',
  child: 'child',
  infant: 'infant_without_seat',
  infant_without_seat: 'infant_without_seat',
};

function _duffelOfferType(value: unknown): DuffelOfferPassenger['type'] {
  if (typeof value !== 'string') return null;
  return DUFFEL_OFFER_TYPE[value.trim().toLowerCase()] ?? null;
}

/**
 * Fields Duffel requires on every order passenger. `identity_documents` and
 * `infant_passenger_id` are conditionally required by the offer and are mapped
 * separately when their data exists.
 */
const REQUIRED_PASSENGER_FIELDS = [
  'id',
  'given_name',
  'family_name',
  'gender',
  'title',
  'born_on',
  'email',
  'phone_number',
] as const;

/** The traveller shape the Flutter funnel collects (checkout payload). */
interface InternalTraveler {
  id?: string;
  passengerId?: string;
  firstName?: string;
  given_name?: string;
  lastName?: string;
  family_name?: string;
  dateOfBirth?: string;
  birthday?: string;
  born_on?: string;
  gender?: string;
  title?: string;
  email?: string;
  phone?: string;
  phone_number?: string;
  documentType?: string;
  documentNumber?: string;
  documentIssueCountry?: string;
  documentExpiry?: string;
  /** Internal classification ('adult' | 'child' | 'infant'). */
  passengerType?: string;
  /** For an infant: the index of the accompanying adult in the traveller list. */
  accompanyingAdultIndex?: number;
  [key: string]: unknown;
}

function _nonEmpty(value: unknown): value is string {
  return typeof value === 'string' && value.trim().length > 0;
}

/** Maps the collected gender ('M'/'F'/'male'/…) to Duffel's 'm'/'f'. */
function _duffelGender(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const normalized = value.trim().toLowerCase();
  if (normalized === 'm' || normalized === 'male') return 'm';
  if (normalized === 'f' || normalized === 'female') return 'f';
  return null;
}

/** Normalises a collected title to Duffel's lowercase set; null when unknown. */
function _duffelTitle(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const normalized = value.trim().toLowerCase();
  return DUFFEL_TITLES.has(normalized) ? normalized : null;
}

/**
 * Builds ONE Duffel order passenger from the internal traveller.
 *
 * Returns the mapped passenger plus the required fields that could not be
 * filled from real collected data. Nothing is invented: a field with no
 * legitimate source stays missing so the caller fails before the provider
 * call instead of sending a payload Duffel would reject.
 */
function toDuffelPassenger(
  traveler: InternalTraveler,
  supportedDocumentTypes?: string[],
): { passenger: Record<string, unknown>; missing: string[] } {
  const id = traveler.id ?? traveler.passengerId;
  const givenName = traveler.given_name ?? traveler.firstName;
  const familyName = traveler.family_name ?? traveler.lastName;
  const bornOn = traveler.born_on ?? traveler.dateOfBirth ?? traveler.birthday;
  const gender = _duffelGender(traveler.gender);
  const title = _duffelTitle(traveler.title);
  const email = traveler.email;
  const rawPhone = traveler.phone_number ?? traveler.phone;
  const countryCode =
    typeof traveler.phoneCountryCode === 'string'
      ? traveler.phoneCountryCode.replace(/^\+/, '').trim()
      : '';
  // Duffel requires E.164. A collected national number is combined with the
  // explicit calling code the funnel collected; a number that already carries
  // '+' is used verbatim. No country code is ever guessed.
  const phone =
    typeof rawPhone === 'string' &&
    rawPhone.trim().length > 0 &&
    !rawPhone.trim().startsWith('+') &&
    countryCode.length > 0
      ? `+${countryCode}${rawPhone.trim()}`
      : rawPhone;

  const passenger: Record<string, unknown> = {
    id,
    given_name: givenName,
    family_name: familyName,
    born_on: bornOn,
    gender,
    title,
    email,
    phone_number: phone,
  };

  // Identity documents are conditionally required by the offer. Map them only
  // when the funnel collected every piece AND the type is one Duffel accepts.
  if (
    _nonEmpty(traveler.documentType) &&
    _nonEmpty(traveler.documentNumber) &&
    _nonEmpty(traveler.documentIssueCountry) &&
    _nonEmpty(traveler.documentExpiry)
  ) {
    const documentType = String(traveler.documentType).trim().toLowerCase();
    // The document type must be accepted by Duffel AND by THIS offer — an
    // offer that only supports `known_traveler_number` would reject a
    // passport, so it is never sent just because Duffel accepts it in general.
    const duffelAccepts = DUFFEL_DOCUMENT_TYPES.has(documentType);
    const offerAccepts =
      !Array.isArray(supportedDocumentTypes) ||
      supportedDocumentTypes.length === 0 ||
      supportedDocumentTypes.includes(documentType);
    if (duffelAccepts && offerAccepts) {
      passenger.identity_documents = [
        {
          type: documentType,
          unique_identifier: String(traveler.documentNumber).trim(),
          issuing_country_code: String(
            traveler.documentIssueCountry,
          ).trim().toUpperCase(),
          expires_on: String(traveler.documentExpiry).trim(),
        },
      ];
    }
  }

  const byField: Record<string, unknown> = {
    id,
    given_name: givenName,
    family_name: familyName,
    gender,
    title,
    born_on: bornOn,
    email,
    phone_number: phone,
  };
  const missing = REQUIRED_PASSENGER_FIELDS.filter(
    (field) => !_nonEmpty(byField[field]),
  );
  return { passenger, missing };
}

/**
 * Booking capability adapter for the Duffel flight provider (Phase 4A).
 *
 * Reuses the EXISTING DuffelService methods (`revalidateOffer`, `createOrder`)
 * — it does not re-implement any provider call. Duffel flights can be booked
 * and revalidated; cancellation is unsupported, so `cancel` is false and the
 * service will surface a structured capability error instead of calling a
 * non-existent path.
 *
 * Payment is deliberately NOT part of this adapter (spec: 4A ships no
 * payment). `createOrder` runs in `instant` mode per existing behaviour.
 */
@Injectable()
export class DuffelBookingProvider implements BookingProvider {
  constructor(private readonly duffel: DuffelService) {}

  readonly providerId = 'duffel-flight';

  get providerName(): string {
    return this.duffel.providerName;
  }

  readonly bookingCapability = {
    book: true,
    cancel: false,
    revalidate: true,
  } as const;

  async revalidateBooking(
    offerId: string,
  ): Promise<ProviderResult<BookingRevalidation>> {
    const result = await this.duffel.revalidateOffer(offerId);
    if (!result.success || !result.data) {
      return {
        success: false,
        providerId: this.providerId,
        providerName: this.providerName,
        error: result.error ?? 'Duffel revalidation failed',
        timestamp: result.timestamp,
      };
    }
    const data = result.data;
    return {
      success: true,
      providerId: this.providerId,
      providerName: this.providerName,
      data: {
        price: Number(data.price ?? 0),
        currency: String(data.currency ?? 'USD'),
        available: data.available !== false && Number(data.price ?? 0) > 0,
        expiresAt: data.expiresAt,
        // P3-D5: the offer passenger ids are the only valid order-passenger
        // ids. They travel through `handoff` into the persisted booking
        // snapshot, so the confirm step never has to re-invent them.
        handoff: {
          duffelPassengers: Array.isArray(data.passengers)
            ? data.passengers
            : [],
          duffelIdentityDocumentsRequired:
            data.passengerIdentityDocumentsRequired === true,
          duffelSupportedDocumentTypes: Array.isArray(
            data.supportedPassengerIdentityDocumentTypes,
          )
            ? data.supportedPassengerIdentityDocumentTypes
            : [],
        },
      },
      timestamp: result.timestamp,
    };
  }

  async createBooking(
    input: CreateBookingInput,
  ): Promise<ProviderResult<CreatedBooking>> {
    const travelers = (input.travelers ?? []) as InternalTraveler[];
    if (travelers.length === 0) {
      return {
        success: false,
        providerId: this.providerId,
        providerName: this.providerName,
        error: 'Duffel booking requires at least one passenger',
        timestamp: new Date(),
      };
    }

    const snapshot = (input.offerSnapshot ?? {}) as Record<string, any>;
    const offerPassengers = Array.isArray(snapshot.duffelPassengers)
      ? (snapshot.duffelPassengers as DuffelOfferPassenger[])
      : [];
    if (offerPassengers.length === 0) {
      return {
        success: false,
        providerId: this.providerId,
        providerName: this.providerName,
        error:
          'Duffel booking is missing the offer passenger ids ' +
          '(offerSnapshot.duffelPassengers). They are captured when the offer ' +
          'is revalidated — revalidate the booking before confirming.',
        timestamp: new Date(),
      };
    }

    // Resolve each traveller to its offer passenger by (type, ordinal within
    // the type). Array order alone is never trusted: the classification comes
    // from the traveller, the identity from the provider's own offer.
    const offerByType: Record<string, DuffelOfferPassenger[]> = {
      adult: [],
      child: [],
      infant_without_seat: [],
    };
    for (const passenger of offerPassengers) {
      if (passenger && passenger.type && offerByType[passenger.type]) {
        offerByType[passenger.type].push(passenger);
      }
    }

    const ordinals: Record<string, number> = {};
    const passengerIds: Array<string | undefined> = [];
    const problems: string[] = [];
    for (let index = 0; index < travelers.length; index++) {
      const type = _duffelOfferType(
        travelers[index].passengerType ?? travelers[index].type,
      );
      if (!type) {
        problems.push(`passenger ${index + 1}: type`);
        passengerIds.push(undefined);
        continue;
      }
      const ordinal = ordinals[type] ?? 0;
      ordinals[type] = ordinal + 1;
      const offer = offerByType[type][ordinal];
      if (!offer) {
        problems.push(
          `passenger ${index + 1}: no ${type} passenger left on the offer`,
        );
        passengerIds.push(undefined);
        continue;
      }
      passengerIds.push(offer.id);
    }

    // Infant → adult association. Duffel links the infant by putting the
    // infant's passenger id on the ADULT (`infant_passenger_id`). The infant
    // must name its own adult explicitly — an arbitrary adult is never picked.
    const infantLinks: Array<{ adultIndex: number; infantId: string }> = [];
    for (let index = 0; index < travelers.length; index++) {
      if (
        _duffelOfferType(
          travelers[index].passengerType ?? travelers[index].type,
        ) !== 'infant_without_seat'
      ) {
        continue;
      }
      const infantId = passengerIds[index];
      const adultIndex = travelers[index].accompanyingAdultIndex;
      const adultType =
        typeof adultIndex === 'number' &&
        adultIndex >= 0 &&
        adultIndex < travelers.length
          ? _duffelOfferType(
              travelers[adultIndex].passengerType ?? travelers[adultIndex].type,
            )
          : null;
      if (
        adultType !== 'adult' ||
        !passengerIds[adultIndex as number] ||
        !infantId
      ) {
        problems.push(
          `passenger ${index + 1}: accompanying adult (infant_passenger_id)`,
        );
        continue;
      }
      if (infantLinks.some((link) => link.adultIndex === adultIndex)) {
        problems.push(
          `passenger ${index + 1}: the accompanying adult already has an infant`,
        );
        continue;
      }
      infantLinks.push({ adultIndex: adultIndex as number, infantId });
    }

    // Every offer passenger must be claimed by exactly one traveller — a short
    // party would silently drop a seat the traveller already paid for.
    const claimed = new Set(
      passengerIds.filter((id): id is string => typeof id === 'string'),
    );
    if (claimed.size !== offerPassengers.length) {
      problems.push(
        `the offer has ${offerPassengers.length} passengers but ` +
          `${claimed.size} were supplied`,
      );
    }

    // Map first, then validate: a required field with no real source must fail
    // BEFORE the provider call, never as a malformed payload Duffel rejects.
    // Passenger order is preserved (the array is mapped positionally).
    const passengers: Array<Record<string, unknown>> = [];
    const missingByPassenger: Array<{ index: number; fields: string[] }> = [];
    const supportedDocumentTypes = Array.isArray(
      snapshot.duffelSupportedDocumentTypes,
    )
      ? (snapshot.duffelSupportedDocumentTypes as string[])
      : undefined;
    const documentsRequired = snapshot.duffelIdentityDocumentsRequired === true;
    for (let index = 0; index < travelers.length; index++) {
      const { passenger, missing } = toDuffelPassenger(
        { ...travelers[index], id: passengerIds[index] },
        supportedDocumentTypes,
      );
      passengers.push(passenger);
      if (documentsRequired && !passenger.identity_documents) {
        missing.push('identity_documents');
      }
      if (missing.length > 0) {
        missingByPassenger.push({ index, fields: missing });
      }
    }

    // Apply the infant links AFTER the passengers exist (the adult carries the
    // infant's id). This is a Duffel contract property, never an internal name.
    for (const { adultIndex, infantId } of infantLinks) {
      passengers[adultIndex].infant_passenger_id = infantId;
    }

    if (problems.length > 0 || missingByPassenger.length > 0) {
      const details = [
        ...problems,
        ...missingByPassenger.map(
          ({ index, fields }) => `passenger ${index + 1}: ${fields.join(', ')}`,
        ),
      ].join('; ');
      return {
        success: false,
        providerId: this.providerId,
        providerName: this.providerName,
        error:
          `Duffel booking has invalid passenger data (${details}). ` +
          'Collect it in the passenger form — no values are invented.',
        timestamp: new Date(),
      };
    }

    try {
      const order: any = await this.duffel.createOrder(
        input.offerId,
        passengers,
        [],
      );
      const reference =
        order?.booking_reference ?? order?.id ?? String(order?.id ?? '');
      return {
        success: true,
        providerId: this.providerId,
        providerName: this.providerName,
        data: {
          reference: String(reference),
          providerBookingId: order?.id,
          status: order?.status,
          amount: order?.total_amount ? Number(order.total_amount) : undefined,
          currency: order?.total_currency,
          raw: order,
        },
        timestamp: new Date(),
      };
    } catch (error) {
      return {
        success: false,
        providerId: this.providerId,
        providerName: this.providerName,
        error: (error as Error).message,
        timestamp: new Date(),
      };
    }
  }

  async cancelBooking(
    _input: CancelBookingInput,
  ): Promise<ProviderResult<{ cancelled: boolean }>> {
    return {
      success: false,
      providerId: this.providerId,
      providerName: this.providerName,
      error: 'Duffel cancellation is not supported',
      timestamp: new Date(),
    };
  }
}
