/// Bundled Explore catalog — data generation support.
///
/// This file is the hand-written half of the catalog. The canonical city list
/// is generated (see `tool/explore_catalog/generate_catalog.py`); this file
/// holds the surrounding data model and lookups that the generator emits
/// against, plus the curated Home selection.
///
/// See `explore_catalog_data.dart` for the generated list.
library;

import 'package:flutter/foundation.dart';

/// A city in the Explore catalog.
@immutable
class ExploreCity {
  const ExploreCity({
    required this.id,
    required this.name,
    required this.country,
    required this.region,
    required this.asset,
    this.subtitle,
    this.tags = const <String>[],
    this.audiences = const <String>[],
    this.imageCredit,
    this.imageLicense,
    this.imageSource,
  });

  /// Stable, unique, slug-shaped city id (e.g. `cairo`, `new_york`).
  ///
  /// This is the key the image registry resolves, so it never changes once
  /// published. Renaming a city means adding a new id, not editing this one.
  final String id;

  /// English display name, exactly as the traveller knows the city.
  final String name;

  /// Country name. The card shows it as the region line.
  final String country;

  /// Geographic region bucket, used for the catalog's diversity reporting.
  final String region;

  /// Bundled asset path, relative to the asset root (`assets/...`).
  final String asset;

  /// Optional short supporting line. Null keeps the card to name + country.
  final String? subtitle;

  /// Mood tags the Explore page filters on (`beach`, `city`, `nature`, ...).
  final List<String> tags;

  /// Audience tags the Explore page filters on (`families`, `honeymoon`, ...).
  final List<String> audiences;

  /// Photo attribution, from the verified asset manifest. Shown on the city
  /// page; never invented.
  final String? imageCredit;

  /// License name of the bundled photo (e.g. `CC BY-SA 4.0`).
  final String? imageLicense;

  /// Source file page of the bundled photo, opened by the credit's tap.
  final String? imageSource;

  /// True when the city is one of the curated Home rail selections.
  bool get isCurated => curatedHomeCityIds.contains(id);
}

