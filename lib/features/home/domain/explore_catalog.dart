  for (final String id in curatedHomeCityIds)
    for (final ExploreCity city in kExploreCities)
      if (city.id == id) city,
];

/// Looks a city up by its stable id. Returns null for an unknown id.
ExploreCity? exploreCityById(String id) {
  for (final ExploreCity city in kExploreCities) {
    if (city.id == id) return city;
  }
  return null;
}

