#!/usr/bin/env python3
"""Mirror the dark app icon into Android's night resources.

`flutter_launcher_icons` generates only one adaptive-icon set. TokiGo wants
the launcher icon to invert with the system appearance, so the light set is
generated by that tool and this script fills in the `-night` qualifiers:

  mipmap-night-*/ic_launcher.png              black field, white parasol
  drawable-night-*/ic_launcher_foreground.png transparent, white parasol

`values-night/colors.xml` also has to override `ic_launcher_background` with
#000000 (the light `values/colors.xml` is #FFFFFF). That XML lives in the
repo; this script only writes the rasters.

Run it AFTER `dart run flutter_launcher_icons`:

    python tool/branding/generate_app_icon.py
    dart run flutter_launcher_icons
    python tool/branding/sync_android_night_icons.py

Usage:  python tool/branding/sync_android_night_icons.py
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

RES = Path("android/app/src/main/res")
DARK_LEGACY = Path("assets/icon/app_icon_dark_1024.png")
DARK_FOREGROUND = Path("assets/icon/app_icon_adaptive_dark_foreground_1024.png")

# directory suffix -> raster size (the same sizes flutter_launcher_icons uses)
LEGACY = {
    "mdpi": 48,
    "hdpi": 72,
    "xhdpi": 96,
    "xxhdpi": 144,
    "xxxhdpi": 192,
}
FOREGROUND = {
    "mdpi": 108,
    "hdpi": 162,
    "xhdpi": 216,
    "xxhdpi": 324,
    "xxxhdpi": 432,
}


def _resize(source: Path, size: int) -> Image.Image:
    if not source.exists():
        raise SystemExit(f"missing {source} (run from the repo root)")
    image = Image.open(source).convert("RGBA")
    return image.resize((size, size), Image.Resampling.LANCZOS)


def main() -> int:
    for density, size in LEGACY.items():
        out = RES / f"mipmap-night-{density}" / "ic_launcher.png"
        out.parent.mkdir(parents=True, exist_ok=True)
        _resize(DARK_LEGACY, size).save(out, format="PNG", optimize=True)
        print(f"{out} ({size}x{size})")

    for density, size in FOREGROUND.items():
        out = RES / f"drawable-night-{density}" / "ic_launcher_foreground.png"
        out.parent.mkdir(parents=True, exist_ok=True)
        _resize(DARK_FOREGROUND, size).save(out, format="PNG", optimize=True)
        print(f"{out} ({size}x{size})")

    print("now ensure values-night/colors.xml sets ic_launcher_background to #000000")
    return 0


if __name__ == "__main__":
    sys.exit(main())
